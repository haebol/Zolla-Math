export function generateBlogPostText(
  bundle: BlogPostBundle,
  allCards: ConceptCard[],
  useEasyTip: boolean,
  chapterIdx = 0
): { title: string; body: string } {
  const unitMeta =
    bundle.kind === 'intro' ? null : UNIT_METADATA[bundle.kind as UnitId];
  const unitCardCount = unitMeta
    ? allCards.filter((c) => c.cardCode.startsWith(unitMeta.id)).length
    : 0;

  const formatCardsForChapter = (ch: BlogChapterTemplate) => {
    const chCards = ch.cardIds
      .map((id) => allCards.find((c) => c.id === id))
      .filter((c): c is ConceptCard => Boolean(c));

    return chCards
      .map((c) => {
        const cleanTitle = c.title.replace(/\[\[(\d+)\/(\d+)\]\]/g, '$2분의 $1');
        const rawTip = useEasyTip && c.easyTipText ? c.easyTipText : c.tipText;
        const cleanTip = rawTip
          .replace(/\[\[(\d+)\|(\d+)\/(\d+)\]\]/g, '$1과 $3분의 $2')
          .replace(/\[\[(\d+)\/(\d+)\]\]/g, '$2분의 $1')
          .replace(/\{\{(.*?)\}\}/g, '$1')
          .replace(/\n+/g, ' ');
        return `  • [${c.cardCode.slice(-2)}번 · ${c.badgeLabel}] ${cleanTitle}\n    → 핵심 한 줄: ${cleanTip}`;
      })
      .join('\n');
  };

  // Pinpoint rule: 3-2-4 분수 generates 6 separate standalone lesson-archive blog posts (1편~6편)
  if (bundle.kind === '3-2-4') {
    const ch = bundle.chapters[chapterIdx] ?? bundle.chapters[0];
    const chCards = ch.cardIds
      .map((id) => allCards.find((c) => c.id === id))
      .filter((c): c is ConceptCard => Boolean(c));

    const sub = ch.lessonSubheadings ?? {
      goal: '오늘의 수업 목표와 개념 연결',
      records: '포카 순서대로 정리한 수업 기록',
      share: bundle.outroTitle,
      reflection: '수업을 마치며 남기는 기록',
    };

    const perCardBlocks = chCards
      .map((c, idx) => {
        const rec = ch.cardRecords?.[c.id];
        const cleanTitle = c.title.replace(/\[\[(\d+)\/(\d+)\]\]/g, '$2분의 $1');
        const rawTip = useEasyTip && c.easyTipText ? c.easyTipText : c.tipText;
        const cleanTip = rawTip
          .replace(/\[\[(\d+)\|(\d+)\/(\d+)\]\]/g, '$1과 $3분의 $2')
          .replace(/\[\[(\d+)\/(\d+)\]\]/g, '$2분의 $1')
          .replace(/\{\{(.*?)\}\}/g, '$1')
          .replace(/\n+/g, ' ');

        return [
          `[${idx + 1}번째 포카 사진 — ${c.cardCode.slice(-2)}번 · ${cleanTitle}]`,
          `- 개념 설명: ${rec?.concept ?? cleanTip}`,
          `- 학생의 어려움: ${rec?.difficulty ?? ch.difficultyText}`,
          `- 이렇게 물어봤어요: ${rec?.question ?? ch.tipText}`,
        ].join('\n');
      })
      .join('\n\n');

    const body = [
      ch.postIntro ?? bundle.introParagraph,
      '',
      `[1×1 대표 이미지]`,
      '',
      `🌙 ${sub.goal}`,
      ch.lessonGoal ?? '',
      '',
      `[교과서의 해당 개념 설명 부분 캡처]`,
      '',
      ch.lessonGoalConnection ?? '',
      '',
      `[양면 책자로 출력한 실제 학습지 사진]`,
      '',
      `🌙 ${sub.records}`,
      perCardBlocks,
      '',
      `🌙 ${sub.share}`,
      bundle.outroText,
      '',
      `🌙 ${sub.reflection}`,
      `- 학생의 반응과 이해 정도: (실제 수업 후 관찰한 반응 기록)`,
      `- 효과적이었던 설명과 발문: (수업 중 학생 이해를 도왔던 표현 기록)`,
      `- 강사로서 아쉬웠던 점과 반성: (설명 속도나 발문에서 보완할 점 기록)`,
      `- 다음 수업에서 보완하거나 시도할 내용: (다음 차시에 이어 갈 지도 계획 기록)`,
      '',
      ch.closingGreeting ?? '',
      '',
      bundle.hashtags,
    ]
      .filter((line, idx, arr) => !(line === '' && arr[idx - 1] === ''))
      .join('\n');

    return {
      title: ch.postTitle ?? bundle.defaultTitle,
      body,
    };
  }

  const chapterBlocks = bundle.chapters
    .map((ch) => {
      const cardLines = formatCardsForChapter(ch);

      return [
        `━━━━━━━━━━━━━━━━━━━━━━`,
        `📌 ${ch.title}`,
        ``,
        `[포함 개념 포토카드 미리보기 PNG 첨부 위치]`,
        cardLines,
        ``,
        `😓 ${ch.difficultyTitle}`,
        `${ch.difficultyText}`,
        ``,
        `💡 ${ch.tipTitle}`,
        `${ch.tipText}`,
      ].join('\n');
    })
    .join('\n\n');

  const bodyParts = [
    bundle.introParagraph,
    '',
    unitMeta ? `📚 구성: ${unitMeta.fullLabel} (총 ${unitCardCount}장)` : '',
    '',
    chapterBlocks,
    '',
    `━━━━━━━━━━━━━━━━━━━━━━`,
    `🎁 ${bundle.outroTitle}`,
    bundle.outroText,
    '',
    bundle.hashtags,
  ].filter((line, idx, arr) => !(line === '' && arr[idx - 1] === ''));

  return {
    title: bundle.defaultTitle,
    body: bodyParts.join('\n'),
  };
}
